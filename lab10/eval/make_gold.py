def norm(s):
    return re.sub(r"\s+", " ", s.lower().replace("’", "'").replace("́", "")).strip()


def main():
    docs = {}
    for l in open(LAB / "data" / "docs.jsonl", encoding="utf-8"):
        d = json.loads(l)
        docs[d["doc_id"]] = d
    out, bad = [], []
    for i, (typ, q, ev) in enumerate(G, 1):
        evs = []
        for doc, quote in ev:
            found = any(norm(quote) in norm(p) for _, ps in docs[doc]["sections"] for p in ps)
            if not found:
                bad.append((i, doc, quote))
            evs.append({"doc_id": doc, "quote": quote})
        out.append({"qid": f"G{i:02d}", "type": typ, "query": q, "evidence": evs,
                    "source": "LLM-чернетка (Claude) → перевірка цитат у корпусі"})
    with open(LAB / "eval" / "gold.jsonl", "w", encoding="utf-8") as f:
        for x in out:
            f.write(json.dumps(x, ensure_ascii=False) + "\n")
    print(f"{len(out)} запитів; типи:", {t: sum(x['type'] == t for x in out) for t in ("keyword", "paraphrase", "multihop", "noanswer")})
    print("не знайдено цитат:", bad)
    return bad


if __name__ == "__main__":
    main()
