G = G.loc[~pd.Series(["||".join(sorted(x)) for x in zip(G.a, G.b)]).duplicated().values].reset_index(drop=True)
rng = np.random.default_rng(14)
G["split"] = ""
for l in (0, 1):
    idx = np.array(G.index[G.label == l])
    rng.shuffle(idx)
    G.loc[idx[::2], "split"] = "dev"
    G.loc[idx[1::2], "split"] = "test"
G["annotator"] = "LLM-експерт (Claude) за правилом sameAs; переглядає студент"
G.insert(0, "pair_id", [f"P{i + 1:03d}" for i in range(len(G))])
G.to_csv(LAB / "quality" / "pairs_gold.csv", index=False)
