         ("Флоренс Найтінгейл", "ЛР13", "Найтінгейл", "ЛР13", 1, "прізвище без імені"),
         ("Національний фонд", "ЛР13", "Національний фонд в підтримку демократії", "ЛР13", 1, "скорочена назва (W14)"),
         ("Могилянської школи журналістики", "ЛР13", "Могилянська школа журналістики (НаУКМА)", "ЛР13", 1, "відмінкова форма"),
         ("Офісу генерального прокурора України", "ЛР13", "Департамент міжнародно-правової співпраці та повернення активів Офісу генерального прокурора України", "ЛР13", 0, "ціле ≠ підрозділ"),
         ("реверсивний пошук", "ЛР13", "Реверсивний пошук зображень", "ЛР9", 1, "той самий інструмент"),
         ("JEIDA", "ЛР13", "JEITA", "ЛР13", 0, "різні асоціації (наступниця)"),
         ("ДНР", "ЛР13", "ЛНР", "ЛР13", 0, "різні утворення"),
