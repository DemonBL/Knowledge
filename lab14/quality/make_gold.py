R = dedup.load_registry()
rows = []
for a, sa, b, sb, l, n in EXTRA:
    ra = next(r for r in R if r["name"] == a and r["source"].startswith(sa))
    rb = next(r for r in R if r["name"] == b and r["source"].startswith(sb))
    rows.append(dict(a=ra["rid"], b=rb["rid"], name_a=a, name_b=b, type_a=ra["type"], type_b=rb["type"],
                     src_a=ra["source"], src_b=rb["source"], label=l, note=n))
cols = ["a", "b", "name_a", "name_b", "type_a", "type_b", "src_a", "src_b", "label", "note"]
